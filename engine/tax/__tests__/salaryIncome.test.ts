/**
 * 給与所得(給与所得控除後)の区分表テスト — 令和8・9年分。
 * 根拠: 国税庁「源泉所得税の改正のあらまし」(令和8年4月)
 * https://www.nta.go.jp/publication/pamph/gensen/2026kaisei.pdf
 */

import { describe, expect, test } from "vitest";
import rules2026 from "../../../rules/2026.json";
import type { RuleSet } from "../../types/index.js";
import { salaryIncome } from "../salaryIncome.js";

const incomeTaxRules = (rules2026 as RuleSet).incomeTax;

describe("給与所得の計算(令和8・9年分の区分表)", () => {
  test.each([
    // [収入金額, 期待される給与所得]
    [0, 0],
    [740999, 0], // 最低保障74万円(74万1,000円未満は給与所得なし)
    [741000, 1000], // 収入 − 74万
    [2190999, 1450999],
    [2191000, 1451000], // 特別区分(固定額)
    [2193000, 1453000],
    [2196000, 1456000],
    [2199999, 1456000],
    // 220万以上: A方式 (A = 収入/4 を千円未満切捨て×1000)
    [2200000, 1460000], // A=550,000 → ×2.8−80,000
    [3599999, 2437200], // A=899,000 → 899,000×2.8−80,000 = 2,517,200−80,000
    [3600000, 2440000], // A=900,000 → ×3.2−440,000 = 2,880,000−440,000
    [3999996, 2756800], // A=999,000 → ×3.2−440,000
    [6599999, 4836800], // A=1,649,000 → ×3.2−440,000 = 5,276,800−440,000
    [6600000, 4840000], // ×90%−1,100,000
    [8499999, 6549999], // 8,499,999×0.9−1,100,000 = 7,649,999.1−1,100,000 → floor
    [8500000, 6550000], // 収入−195万
    [15000000, 13050000]
  ])("収入 %i円 → 給与所得 %i円", (gross, expected) => {
    expect(salaryIncome(gross, incomeTaxRules)).toBe(expected);
  });
});
